"""
Markdown → ACM ``acmart`` (acmsmall) LaTeX for the system paper.

The numerical paper's converter (``papers/md_to_latex.py``) is bound to IEEE's
classes, its figure manifest and its Roman table numbers; this one reuses its
inline pass (emphasis, code, Unicode, subscripts, superscripts, escapes) and
handles the structure of ``system_paper_draft.md`` on its own: title, author
line, abstract, keywords, numbered sections and subsections, bold table
captions followed by pipe tables (set with ``tabularx`` so wide tables wrap),
numbered and bulleted lists, fenced code, a numbered reference list, and the
appendix. Bracketed numeric citations become ``\\cite``; ``[verify: ...]``
notes are kept as marginal-free bold text so they cannot be missed in a draft.

Run:
    python papers/system_paper/md_to_acm.py && (cd papers/system_paper && pdflatex system_paper && pdflatex system_paper)
"""

from __future__ import annotations

import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2]))
from papers.md_to_latex import inline  # noqa: E402

HERE = pathlib.Path(__file__).parent
SRC = HERE / "system_paper_draft.md"
OUT = HERE / "system_paper.tex"

PREAMBLE = r"""\documentclass[acmsmall,screen,review]{acmart}
\input{glyphtounicode}
\pdfgentounicode=1
\usepackage{tabularx}
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{ragged2e}
\newcolumntype{Y}{>{\RaggedRight\arraybackslash}X}
\newcolumntype{Z}{>{\RaggedLeft\arraybackslash}X}
\settopmatter{printacmref=false}
\setcopyright{none}
\acmJournal{TQC}
\acmYear{2026}
\begin{document}
"""

# ACM CCS concepts (https://dl.acm.org/ccs): the paper is a software-engineering-for-quantum-computing
# systems paper about verification, provenance and cost control of cloud experiments.
# The CCSXML block (with concept ids) is generated by the ACM CCS tool at camera-ready and pasted here;
# until then only the human-readable \ccsdesc lines are set, which acmart accepts.
CCS = r"""\ccsdesc[500]{Software and its engineering~Software verification and validation}
\ccsdesc[300]{Hardware~Quantum computation}
\ccsdesc[300]{Information systems~Data provenance}
\ccsdesc[300]{General and reference~Experimentation}
"""

NUMBER = re.compile(r"^[\s\d.,%$+\-−·×^⁻⁰¹²³⁴⁵⁶⁷⁸⁹e/:()|≤≥~?—–]*$")


def cite(text: str) -> str:
    """[1] → \\cite{ref1}; [1, Sec. VI-C] → \\cite[Sec.~VI-C]{ref1}; [2], [3] kept separate."""
    def one(m):
        keys = ",".join(f"ref{k.strip()}" for k in m.group(1).split(","))
        if m.group(2):
            return rf"\cite[{m.group(2).strip()}]{{{keys}}}"
        return rf"\cite{{{keys}}}"
    return re.sub(r"\[(\d+(?:\s*,\s*\d+)*)(?:,\s*([^\]\d][^\]]*))?\]", one, text)


def verify_notes(text: str) -> str:
    return re.sub(r"\[verify: ([^\]]*)\]", r"**[VERIFY: \1]**", text)


def breakable(tex: str) -> str:
    """Let long identifiers and paths inside \\texttt break at / _ . and -."""
    def fix(m):
        body = m.group(1)
        if len(body) < 18:
            return m.group(0)
        body = body.replace("/", "/\\allowbreak{}").replace("\\_", "\\_\\allowbreak{}")
        body = body.replace(".", ".\\allowbreak{}").replace("-", "-\\allowbreak{}")
        return "\\texttt{" + body + "}"
    return re.sub(r"\\texttt\{([^{}]*)\}", fix, tex)


def prose(text: str) -> str:
    # Braces are set literally (sets such as N ∈ {12, 16, 20}); the draft
    # writes no LaTeX groups of its own.
    text = text.replace("{", "\\{").replace("}", "\\}")
    return breakable(inline(cite(verify_notes(text))))


def is_row(line: str) -> bool:
    s = line.strip()
    return s.startswith("|") and s.endswith("|") and s.count("|") >= 2


def split_row(line: str) -> list[str]:
    cells = line.strip()[1:-1].split("|")
    return [c.strip() for c in cells]


def table(rows: list[str], caption: str, number: int) -> list[str]:
    parsed = [split_row(r) for r in rows if not re.match(r"^\|[\s:\-|]+\|$", r.strip())]
    head, body = parsed[0], parsed[1:]
    ncol = len(head)
    body = [r + [""] * (ncol - len(r)) for r in body]
    # A column is numeric if every body cell is a number (or empty/dash);
    # text columns share the width.
    numeric = []
    for j in range(ncol):
        cells = [r[j] for r in body if r[j] not in ("", "—", "-", "?")]
        numeric.append(bool(cells) and all(NUMBER.match(c) for c in cells))
    text_cols = [j for j in range(ncol) if not numeric[j]]
    longest = {j: max([len(r[j]) for r in body] + [len(head[j])]) for j in range(ncol)}
    spec = ""
    for j in range(ncol):
        if numeric[j]:
            spec += "r"
        elif longest[j] <= 14 and len(text_cols) > 1:
            spec += "l"
        else:
            spec += "Y"
    if "Y" not in spec:
        spec = spec.replace("l", "Y", 1) if "l" in spec else spec
    env = "tabularx" if "Y" in spec else "tabular"
    width = r"{\textwidth}" if env == "tabularx" else ""
    out = [r"\begin{table}[t]", r"\small", rf"\caption{{{prose(caption)}}}",
           rf"\label{{tab:{number}}}", rf"\begin{{{env}}}{width}{{{spec}}}", r"\toprule",
           " & ".join(rf"\textbf{{{prose(h)}}}" for h in head) + r" \\", r"\midrule"]
    for r in body:
        out.append(" & ".join(prose(c) for c in r) + r" \\")
    out += [r"\bottomrule", rf"\end{{{env}}}", r"\end{table}", ""]
    return out


def convert(md: str) -> str:
    lines = md.split("\n")
    out: list[str] = [PREAMBLE]
    title = next(l[2:].strip() for l in lines if l.startswith("# "))
    out.append(rf"\title{{{prose(title)}}}")
    author = next((l for l in lines if l.startswith("**Author.**")), "")
    m = re.match(r"\*\*Author\.\*\*\s*([^,]+),\s*([^,]+),\s*([^,]+),\s*(.*?)\.?$", author)
    if m:
        out.append(rf"\author{{{m.group(1).strip()}}}")
        out.append(rf"\affiliation{{\institution{{{prose(m.group(2).strip())}}}"
                   rf"\city{{{m.group(3).strip()}}}\country{{{m.group(4).strip()}}}}}")
        out.append(r"\email{tobita-hiroaki@aiit.ac.jp}")

    i = 0
    state = "front"
    abstract: list[str] = []
    keywords = ""
    in_list: str | None = None
    table_no = 0
    pending_caption: str | None = None
    refs: list[tuple[str, str]] = []
    body: list[str] = []

    def close_list():
        nonlocal in_list
        if in_list:
            body.append(rf"\end{{{in_list}}}")
            in_list = None

    while i < len(lines):
        line = lines[i]
        s = line.strip()
        if state == "front":
            if s == "## Abstract":
                state = "abstract"
            i += 1
            continue
        if state == "abstract":
            if s.startswith("**Keywords.**"):
                keywords = s[len("**Keywords.**"):].strip()
                while i + 1 < len(lines) and lines[i + 1].strip() and not lines[i + 1].startswith("---"):
                    i += 1
                    keywords += " " + lines[i].strip()
                keywords = keywords.rstrip(".")
                state = "body"
            elif s and not s.startswith("---"):
                abstract.append(s)
            i += 1
            continue
        if state == "refs":
            m = re.match(r"^\[(\d+)\]\s+(.*)$", s)
            if m:
                text = m.group(2)
                while i + 1 < len(lines) and lines[i + 1].strip() and not lines[i + 1].startswith("[") \
                        and not lines[i + 1].startswith("#") and not lines[i + 1].startswith("---"):
                    i += 1
                    text += " " + lines[i].strip()
                refs.append((m.group(1), text))
            elif s.startswith("## ") or s == "---":
                state = "body"
                continue
            i += 1
            continue

        # body
        if s == "## References":
            close_list()
            state = "refs"
            i += 1
            continue
        if s == "---" or s == "":
            close_list()
            body.append("")
            i += 1
            continue
        if s.startswith("## Appendix "):
            close_list()
            m = re.match(r"^## Appendix ([A-Z])\.\s*(.*)$", s)
            if not body or r"\appendix" not in body:
                body.append(r"\appendix")
            body.append(rf"\section{{{prose(m.group(2))}}}")
            i += 1
            continue
        if s.startswith("## "):
            close_list()
            t = re.sub(r"^\d+\.\s*", "", s[3:])
            body.append(rf"\section{{{prose(t)}}}")
            i += 1
            continue
        if s.startswith("### "):
            close_list()
            t = re.sub(r"^\d+\.\d+\s*", "", s[4:])
            body.append(rf"\subsection{{{prose(t)}}}")
            i += 1
            continue
        if s.startswith("```"):
            close_list()
            block = []
            i += 1
            while i < len(lines) and not lines[i].strip().startswith("```"):
                block.append(lines[i])
                i += 1
            i += 1
            body += [r"\begin{small}\begin{verbatim}"] + block + [r"\end{verbatim}\end{small}"]
            continue
        m = re.match(r"^!\[(.*)\]\((.*)\)\s*$", s)
        if m:
            close_list()
            cap, path = m.group(1), m.group(2)
            fm = re.match(r"^Fig\.\s*(\d+)\.\s*(.*)$", cap)
            num, text = (fm.group(1), fm.group(2)) if fm else ("", cap)
            body += [r"\begin{figure}[t]", r"\centering",
                     rf"\includegraphics[width=\textwidth]{{{path}}}",
                     rf"\caption{{{prose(text)}}}"] + ([rf"\label{{fig:{num}}}"] if num else []) + [r"\end{figure}", ""]
            i += 1
            continue
        if is_row(line):
            close_list()
            rows = []
            while i < len(lines) and is_row(lines[i]):
                rows.append(lines[i])
                i += 1
            table_no += 1
            cap = pending_caption or ""
            pending_caption = None
            body += table(rows, cap, table_no)
            continue
        if re.match(r"^\*\*Table \d+\.\s", s):
            # A bold caption may run over several source lines; it ends at the
            # closing ** (the bold run is the caption, and nothing follows it).
            cap = s
            while not re.search(r"\*\*\s*$", cap) and i + 1 < len(lines) and lines[i + 1].strip():
                i += 1
                cap += " " + lines[i].strip()
            m = re.match(r"^\*\*Table \d+\.\s*(.*?)\*\*\s*$", cap)
            pending_caption = m.group(1) if m else cap
            i += 1
            continue
        m = re.match(r"^(\d+)\.\s+(.*)$", s)
        if m and not s.startswith("**"):
            if in_list != "enumerate":
                close_list()
                body.append(r"\begin{enumerate}")
                in_list = "enumerate"
            item = m.group(2)
            while i + 1 < len(lines) and lines[i + 1].startswith("   ") and lines[i + 1].strip():
                i += 1
                item += " " + lines[i].strip()
            body.append(rf"\item {prose(item)}")
            i += 1
            continue
        if s.startswith("- "):
            if in_list != "itemize":
                close_list()
                body.append(r"\begin{itemize}")
                in_list = "itemize"
            item = s[2:]
            while i + 1 < len(lines) and lines[i + 1].startswith("  ") and lines[i + 1].strip() \
                    and not lines[i + 1].strip().startswith("- "):
                i += 1
                item += " " + lines[i].strip()
            body.append(rf"\item {prose(item)}")
            i += 1
            continue
        # paragraph: join continuation lines
        para = [s]
        while i + 1 < len(lines):
            nxt = lines[i + 1]
            ns = nxt.strip()
            if not ns or ns.startswith(("#", "|", "```", "- ", "---")) or re.match(r"^\d+\.\s", ns) \
                    or re.match(r"^\*\*Table \d+\.", ns):
                break
            i += 1
            para.append(ns)
        close_list()
        body.append(prose(" ".join(para)))
        body.append("")
        i += 1

    out.append(r"\begin{abstract}")
    out.append(prose(" ".join(abstract)))
    out.append(r"\end{abstract}")
    out.append(CCS)
    out.append(rf"\keywords{{{prose(keywords)}}}")
    out.append(r"\maketitle")
    out += body
    out.append(r"\begin{thebibliography}{99}")
    for n, text in refs:
        out.append(rf"\bibitem{{ref{n}}} {prose(text)}")
    out.append(r"\end{thebibliography}")
    out.append(r"\end{document}")
    return "\n".join(out) + "\n"


def main() -> int:
    OUT.write_text(convert(SRC.read_text(encoding="utf-8")))
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
